    private static readonly byte[] AsciiCache = BuildAscii();

    private static byte[] BuildAscii()
    {
        var t = new byte[0x300];
        for (int i = 0; i < t.Length; i++) t[i] = (byte)Compute(i, false);
        return t;
    }

    public static int Of(int cp, bool ambiguousWide = false)
    {
        if (cp < 0x300 && !ambiguousWide) return AsciiCache[cp];
        return Compute(cp, ambiguousWide);
    }

    private static int Compute(int cp, bool ambiguousWide)
    {
        if (cp == 0) return 0;
        if (cp < 0x20 || (cp >= 0x7F && cp < 0xA0)) return 0;
        if (cp < 0x300) return ambiguousWide && InTable(Ambiguous, cp) ? 2 : 1;

        // Hangul Jamo medial vowels / final consonants and zero-width joiners/format characters
        if ((cp >= 0x1160 && cp <= 0x11FF) || cp == 0x200B) return 0;
        if (cp >= 0xD800 && cp <= 0xDFFF) return 1;

        var cat = cp <= 0xFFFF
            ? CharUnicodeInfo.GetUnicodeCategory((char)cp)
            : CharUnicodeInfo.GetUnicodeCategory(cp);
        if (cat is UnicodeCategory.NonSpacingMark or UnicodeCategory.EnclosingMark or UnicodeCategory.Format)
            return 0;

        if (InTable(Wide, cp)) return 2;
        if (ambiguousWide && InTable(Ambiguous, cp)) return 2;
        return 1;
    }

    private static bool InTable(int[] table, int cp)
    {
        int lo = 0, hi = table.Length / 2 - 1;
        if (cp < table[0] || cp > table[^1]) return false;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            if (cp > table[mid * 2 + 1]) lo = mid + 1;
            else if (cp < table[mid * 2]) hi = mid - 1;
            else return true;
        }
        return false;
    }
